"""Minimal structural contracts used by the optional common facade.

These protocols intentionally contain only the small shared surface. Backends
are free to expose much richer expert APIs independently.
"""
from __future__ import annotations
from pathlib import Path
from typing import Any, Iterable, Protocol, runtime_checkable


@runtime_checkable
class DocumentBackend(Protocol):
    format: str
    native: Any

    @property
    def paragraphs(self) -> list[Any]: ...
    @property
    def tables(self) -> list[Any]: ...
    @property
    def sections(self) -> list[Any]: ...
    @property
    def pictures(self) -> list[Any]: ...
    @property
    def styles(self) -> Any: ...
    @property
    def core_properties(self) -> Any: ...
    def add_section(self) -> Any: ...
    def add_paragraph(self, text: str = "", style=None) -> Any: ...
    def add_table(self, rows: int, cols: int, style=None) -> Any: ...
    def add_picture(self, image_data: bytes, image_format: str, *, width=None, height=None, treat_as_char: bool = True) -> Any: ...
    def export_snapshot(self, *, preserve_layout: bool = True) -> Any: ...
    def import_snapshot(self, snapshot: Any, *, preserve_layout: bool = True) -> None: ...
    def replace(self, search: str, replacement: str, *, everywhere: bool = True, count: int = -1) -> int: ...
    def iter_text_paragraphs(self, *, everywhere: bool = True) -> Iterable[Any]: ...
    def iter_tables(self, *, everywhere: bool = True) -> Iterable[Any]: ...
    def save(self, path: str | Path) -> None: ...
    def iter_inner_content(self) -> Iterable[Any]: ...


@runtime_checkable
class ParagraphBackend(Protocol):
    native: Any
    @property
    def structural_token(self) -> Any: ...
    @property
    def text(self) -> str: ...
    @property
    def runs(self) -> list[Any]: ...
    def add_run(self, text: str | None = None, style=None) -> Any: ...
    def clear(self) -> Any: ...
    def replace(self, search: str, replacement: str, count: int = -1) -> int: ...


@runtime_checkable
class TableBackend(Protocol):
    native: Any
    @property
    def rows(self) -> list[Any]: ...
    def cell(self, row: int, col: int) -> Any: ...
    def clone_row(self, index: int) -> Any: ...
    def insert_row(self, index: int, row_token: Any) -> Any: ...
    def remove_row(self, index: int) -> None: ...


@runtime_checkable
class CellBackend(Protocol):
    native: Any
    @property
    def text(self) -> str: ...
    def add_table(self, rows: int, cols: int, style=None) -> Any: ...
    def merge(self, other: Any) -> Any: ...


@runtime_checkable
class StylesBackend(Protocol):
    def __getitem__(self, key: Any) -> Any: ...
    def __iter__(self): ...
    def __len__(self) -> int: ...
    def add_style(self, name: str, style_type: Any, builtin: bool = False, *, clone_from: Any = None) -> Any: ...
    def default(self, style_type: Any) -> Any: ...


@runtime_checkable
class StyleBackend(Protocol):
    native: Any
    @property
    def name(self) -> str | None: ...
    @property
    def style_type(self) -> Any: ...
    @property
    def font(self) -> Any: ...
    @property
    def paragraph_format(self) -> Any: ...
    def delete(self) -> None: ...

@runtime_checkable
class HeaderFooterBackend(Protocol):
    native: Any
    @property
    def text(self) -> str: ...
    @property
    def paragraphs(self) -> list[Any]: ...
    @property
    def tables(self) -> list[Any]: ...
    def add_paragraph(self, text: str = "", style=None) -> Any: ...
    def add_table(self, rows: int, cols: int, style=None, **kwargs) -> Any: ...
    def iter_inner_content(self) -> Iterable[Any]: ...


@runtime_checkable
class SectionBackend(Protocol):
    native: Any
    @property
    def page_width(self) -> Any: ...
    @property
    def page_height(self) -> Any: ...
    @property
    def left_margin(self) -> Any: ...
    @property
    def right_margin(self) -> Any: ...
    @property
    def top_margin(self) -> Any: ...
    @property
    def bottom_margin(self) -> Any: ...
    @property
    def header_distance(self) -> Any: ...
    @property
    def footer_distance(self) -> Any: ...
    @property
    def gutter(self) -> Any: ...
    @property
    def orientation(self) -> Any: ...
    @property
    def header(self) -> HeaderFooterBackend: ...
    @property
    def footer(self) -> HeaderFooterBackend: ...
    @property
    def even_page_header(self) -> HeaderFooterBackend: ...
    @property
    def even_page_footer(self) -> HeaderFooterBackend: ...


@runtime_checkable
class PictureBackend(Protocol):
    native: Any
    @property
    def width(self) -> Any: ...
    @property
    def height(self) -> Any: ...
    @property
    def size(self) -> tuple[Any, Any]: ...
    def resize(self, *, width=None, height=None) -> Any: ...
